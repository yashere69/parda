"""Regenerate results/benchmark.md.

python tools/benchmark.py            # simulated round trip, no network
PARDA_API_KEY=... python tools/benchmark.py --endpoint <base-url> --model <name>
"""

from __future__ import annotations

import argparse
from pathlib import Path

from parda.bench import corpus, detection, false_restores, live_roundtrip, roundtrip

ROOT = Path(__file__).resolve().parent.parent


def pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "n/a"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=600)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--endpoint")
    ap.add_argument("--model")
    args = ap.parse_args()

    samples = corpus(args.n, args.seed)
    det = detection(samples)
    lines = [
        "# parda benchmark",
        "",
        f"Generated by `python tools/benchmark.py` (n={args.n}, seed={args.seed}). The corpus "
        "is synthetic: Hinglish and Hindi message templates with generated identifiers, "
        "plus negative messages containing order ids, invoice numbers, prices and dates.",
        "",
        "## Detection",
        "",
        "| Kind | Precision | Recall | TP | FP | FN |",
        "|---|---|---|---|---|---|",
    ]
    for kind, c in sorted(det["per_kind"].items()):
        lines.append(
            f"| {kind} | {pct(c['tp'], c['tp'] + c['fp'])} | {pct(c['tp'], c['tp'] + c['fn'])} "
            f"| {c['tp']} | {c['fp']} | {c['fn']} |"
        )
    lines += ["", "| Surface form | Found |", "|---|---|"]
    for form, (ok, total) in sorted(det["by_form"].items()):
        lines.append(f"| {form} | {ok}/{total} |")
    rt = roundtrip(samples)
    lines += [
        "",
        "## Round trip",
        "",
        "Share of replies in which every original value is restored, after the reply's "
        "tokens are rewritten the way a model might rewrite them. Simulated rewrites, not a "
        "real model.",
        "",
        "| Rewrite | Exact-match restore | parda restore |",
        "|---|---|---|",
    ]
    for name in rt["exact match"]:
        lines.append(f"| {name} | {rt['exact match'][name]}% | {rt['parda restore'][name]}% |")
    lines += [
        "",
        f"Replies mentioning a token index that was never issued and still got a value "
        f"filled in: {false_restores(samples)}.",
    ]
    if args.endpoint and args.model:
        live = live_roundtrip(samples, args.endpoint, args.model)
        lines += [
            "",
            f"## Live round trip: {args.model}",
            "",
            f"Sent {live['sent']}; all values restored in {live['all_restored']}; model "
            f"dropped every token in {live['dropped']}; unknown tokens seen "
            f"{live['unknown_tokens']}.",
        ]
    out = ROOT / "results" / "benchmark.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(out.read_text())


if __name__ == "__main__":
    main()
