"""parda and Microsoft Presidio on the same messages, for the kinds both detect.

Presidio is set up the way an Indian deployment would set it up: the default English
registry plus its Indian recognizers (Aadhaar, PAN, GSTIN), with spaCy's en_core_web_sm.
Both are scored on the benchmark corpus (the text parda was tuned on) and on
examples/heldout.jsonl (written afterwards, in other words). Writes results/presidio.md.

    pip install presidio-analyzer
    pip install https://github.com/explosion/spacy-models/releases/download/en_core_web_sm-3.8.0/en_core_web_sm-3.8.0-py3-none-any.whl
    python tools/compare_presidio.py
"""

from __future__ import annotations

import json
import re
import sys
from importlib.metadata import version
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from presidio_analyzer import AnalyzerEngine, RecognizerRegistry  # noqa: E402
from presidio_analyzer.nlp_engine import NlpEngineProvider  # noqa: E402
from presidio_analyzer.predefined_recognizers import (  # noqa: E402
    InAadhaarRecognizer,
    InGstinRecognizer,
    InPanRecognizer,
)

from parda.bench import corpus  # noqa: E402
from parda.detect import detect  # noqa: E402

KINDS = {"IN_AADHAAR": "AADHAAR", "IN_PAN": "PAN", "IN_GSTIN": "GSTIN", "PHONE_NUMBER": "PHONE"}
DIGITS = str.maketrans("०१२३४५६७८९", "0123456789")


def canon(kind: str, raw: str) -> str:
    if kind in ("AADHAAR", "PHONE"):
        d = re.sub(r"\D", "", raw.translate(DIGITS))
        return d if kind == "AADHAAR" else d[-10:]
    return raw.upper()


def engine() -> AnalyzerEngine:
    nlp = NlpEngineProvider(
        nlp_configuration={
            "nlp_engine_name": "spacy",
            "models": [{"lang_code": "en", "model_name": "en_core_web_sm"}],
        }
    ).create_engine()
    registry = RecognizerRegistry()
    registry.load_predefined_recognizers(nlp_engine=nlp)
    for rec in (InAadhaarRecognizer(), InPanRecognizer(), InGstinRecognizer()):
        registry.add_recognizer(rec)
    return AnalyzerEngine(nlp_engine=nlp, registry=registry)


def score(samples: list[tuple[str, set]], find) -> dict[str, list[int]]:
    per = {k: [0, 0, 0] for k in KINDS.values()}
    for text, truth in samples:
        got = {x for x in find(text) if x[0] in per}
        want = {x for x in truth if x[0] in per}
        for k, _ in got & want:
            per[k][0] += 1
        for k, _ in got - want:
            per[k][1] += 1
        for k, _ in want - got:
            per[k][2] += 1
    return per


def cell(tp: int, fp: int, fn: int) -> str:
    p = tp / (tp + fp) if tp + fp else 1.0
    r = tp / (tp + fn) if tp + fn else 1.0
    return f"{p:.0%} / {r:.0%}"


def main() -> None:
    pres = engine()

    def presidio_at(threshold: float):
        def find(text: str) -> set:
            return {
                (KINDS[r.entity_type], canon(KINDS[r.entity_type], text[r.start : r.end]))
                for r in pres.analyze(text, language="en", score_threshold=threshold)
                if r.entity_type in KINDS
            }

        return find

    def parda(text: str) -> set:
        return {(s.kind, s.value) for s in detect(text)}

    sets = {
        "benchmark corpus (n=600, seed 7)": [(s.text, set(s.truth)) for s in corpus()],
        "held-out set": [
            (row["text"], {tuple(t) for t in row["truth"]})
            for row in map(
                json.loads, (ROOT / "examples/heldout.jsonl").read_text("utf-8").splitlines()
            )
        ],
    }
    lines = [
        "# parda and Presidio",
        "",
        "Generated by `python tools/compare_presidio.py`. Do not edit by hand.",
        "",
        f"presidio-analyzer {version('presidio-analyzer')}, spaCy {version('spacy')} with "
        "en_core_web_sm, Indian recognizers added, at the default score threshold and at "
        "0.5. Each cell is precision / recall; a match needs the right kind and the same "
        "normalised value.",
        "",
    ]
    for name, samples in sets.items():
        a = score(samples, parda)
        b, c = score(samples, presidio_at(0.0)), score(samples, presidio_at(0.5))
        lines += [
            f"## {name}",
            "",
            "| Kind | parda | Presidio | Presidio, score ≥ 0.5 |",
            "|---|---|---|---|",
        ]
        for k in KINDS.values():
            lines.append(f"| {k} | {cell(*a[k])} | {cell(*b[k])} | {cell(*c[k])} |")
        lines.append("")
    (ROOT / "results/presidio.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
